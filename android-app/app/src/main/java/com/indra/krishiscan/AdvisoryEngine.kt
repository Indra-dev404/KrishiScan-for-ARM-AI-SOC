package com.indra.krishiscan

import android.content.Context
import android.os.SystemClock
import android.util.Log
import org.pytorch.executorch.ExecutorchRuntimeException
import org.pytorch.executorch.extension.llm.LlmCallback
import org.pytorch.executorch.extension.llm.LlmModule
import java.io.File
import java.io.FileOutputStream

/**
 * Sprint Phase 2, Day 1 (Fri 23 Oct): integrate the ExecuTorch LLM runner into
 * KrishiScan's own app, in a class SEPARATE from [VisionEngine].
 *
 * The hackathon PS requires the vision and Llama pipelines to be documented as
 * separate pipelines, so they are built as separate classes — not just described
 * that way afterwards. A camera photo enters [VisionEngine] and never reaches
 * Llama as an image; Llama receives only text (diagnosis, severity, region,
 * language, verified advisory facts), and that text pipeline starts here.
 *
 * API provenance (so future-you trusts the signatures):
 * - `org.pytorch.executorch.extension.llm.LlmModule` ships inside the
 *   `org.pytorch:executorch-android` AAR — NO new Gradle dependency was added.
 * - Signatures verified against the pytorch/executorch v1.5.1 tag (the exact
 *   version this scaffold pins): `LlmModule(modulePath, tokenizerPath,
 *   temperature)` defaults to MODEL_TYPE_TEXT, `load()`, `generate(prompt,
 *   seqLen, callback, echo)`, `stop()`, `close()`, and `LlmCallback`
 *   with `onResult(String)` required, `onStats(String JSON)` and
 *   `onError(Int, String)` optional. Checked 23 Oct 2026.
 *
 * Threading contract (from the SDK source):
 * - Call `load()` and `generate()` OFF the main thread — both block, and the
 *   model load is a multi-second cold start.
 * - Callbacks arrive on a native thread; this class serialises them.
 * - Never call LlmModule methods from inside a callback (the SDK throws).
 *
 * Generation settings stay conservative per the sprint plan: low temperature
 * (0.3), a hard token cap per call. The grounded prompt builder is a later
 * task — this class takes the assembled prompt as-is, today the smoke
 * test only proves the runner loads and talks.
 *
 * Setup: the .pte + tokenizer come from
 *   huggingface-cli download executorch-community/Llama-3.2-1B-Instruct-SpinQuant_INT4_EO8-ET
 * Either drop them at app/src/main/assets/models/ and rebuild (make the local
 * file names match the constructor defaults below), or — better for a 1.14 GB
 * file — push them straight into the app's files dir via adb run-as (debug
 * build), skipping the rebuild and the doubled footprint. `LlmModule` needs
 * a real file path, so assets are copied out once, exactly like
 * [VisionEngine] does.
 *
 * Licence: advisory text is generated by Llama 3.2 — the app keeps "Built with
 * Llama" attribution (NOTICE + placement guide delivered 20 Oct).
 */
class AdvisoryEngine(
    private val context: Context,
    private val modelAssetName: String = "models/Llama-3.2-1B-Instruct-SpinQuant_INT4_EO8.pte",
    private val tokenizerAssetName: String = "models/tokenizer.model",
    private val temperature: Float = 0.3f,
) {

    companion object {
        private const val TAG = "AdvisoryEngine"

        /** The quantised 1B build's context window (per the HF model card). */
        const val MAX_CONTEXT_TOKENS = 8192

        /** Llama 3 special tokens that can leak into streamed output; stripped. */
        private val SPECIAL_TOKENS = listOf(
            "<|begin_of_text|>",
            "<|start_header_id|>",
            "<|end_header_id|>",
            "<|eot_id|>",
        )
    }

    /** One completed generation, with the numbers the measurement day needs. */
    data class Advisory(
        /** Generated text with Llama 3 special tokens stripped. */
        val text: String,
        /** Tokens the model produced (counts onResult calls). */
        val outputTokens: Int,
        /** ms from generate() entry to the first token — the sprint's TTFT. */
        val timeToFirstTokenMs: Long,
        /** Decode speed over the post-first-token window. */
        val decodeTokensPerSec: Double,
        /** Wall-clock ms for the whole generate() call. */
        val totalMs: Long,
        /** Raw stats JSON from the SDK's onStats (tokens_per_second etc.). */
        val statsJson: String,
    )

    private var module: LlmModule? = null

    /** Cold-load wall time in ms, valid after [load]. */
    var loadTimeMs: Long = -1L
        private set

    /**
     * Copies model + tokenizer out of assets if they aren't already in the app's
     * files dir, then constructs and force-loads the LlmModule. OFF main thread.
     * Throws [IllegalStateException] with setup instructions if a file is missing.
     */
    fun load() {
        check(module == null) { "load() called twice — close() first." }
        val modelPath = resolveFile(modelAssetName)
        val tokenizerPath = resolveFile(tokenizerAssetName)
        Log.i(TAG, "loading Llama: $modelPath")
        val t0 = SystemClock.elapsedRealtime()
        try {
            val m = LlmModule(modelPath, tokenizerPath, temperature)
            m.load() // force now; otherwise the model loads on first generate()
            module = m
        } catch (e: ExecutorchRuntimeException) {
            throw IllegalStateException(
                "Llama .pte failed to load (${e.message}). " +
                    "If this is a version error, grep logcat for \"Program schema version\".",
                e,
            )
        }
        loadTimeMs = SystemClock.elapsedRealtime() - t0
        Log.i(TAG, "Llama loaded in $loadTimeMs ms")
    }

    /**
     * Runs one grounded advisory generation. BLOCKS the calling thread — call
     * off the main thread. Returns the text plus the timing numbers for the
     * dashboard. Throws if [load] hasn't succeeded.
     */
    fun generate(prompt: String, maxNewTokens: Int = 256): Advisory {
        val m = module
            ?: throw IllegalStateException("generate() before load(). Call load() first.")

        // seqLen covers prompt + new tokens; the prompt length is estimated at
        // ~4 chars/token for English advisory text.
        val seqLen = (prompt.length / 4 + 8 + maxNewTokens).coerceAtMost(MAX_CONTEXT_TOKENS)

        val text = StringBuilder()
        val lock = Any()
        var firstTokenMs = -1L
        var tokens = 0
        var statsJson = ""
        val t0 = SystemClock.elapsedRealtime()

        val callback = object : LlmCallback {
            override fun onResult(result: String) {
                synchronized(lock) {
                    if (firstTokenMs < 0) firstTokenMs = SystemClock.elapsedRealtime() - t0
                    text.append(result)
                    tokens++
                }
            }

            override fun onStats(stats: String) {
                statsJson = stats
            }

            override fun onError(errorCode: Int, message: String) {
                Log.e(TAG, "generate onError code=$errorCode msg=$message")
            }
        }

        // echo=false: chat mode, don't re-emit the prompt.
        m.generate(prompt, seqLen, callback, false)

        val totalMs = SystemClock.elapsedRealtime() - t0
        val ttft = firstTokenMs
        val decodeMs = (if (ttft >= 0) totalMs - ttft else totalMs).coerceAtLeast(1L)
        val cleaned = stripSpecialTokens(text.toString())

        return Advisory(
            text = cleaned,
            outputTokens = tokens,
            timeToFirstTokenMs = ttft,
            decodeTokensPerSec = tokens * 1000.0 / decodeMs,
            totalMs = totalMs,
            statsJson = statsJson,
        )
    }

    /** Cancels an in-flight generate(). Safe to call any time. */
    fun stop() {
        module?.stop()
    }

    /** Releases the native model. Call when the advisory pipeline is torn down. */
    fun close() {
        module?.close()
        module = null
    }

    /**
     * LlmModule needs a real file path; APK assets may be compressed, so the
     * file is copied to the app's files dir once — the same pattern as
     * [VisionEngine]. A file already in filesDir (sideloaded) is used as-is.
     */
    private fun resolveFile(assetName: String): String {
        val out = File(context.filesDir, assetName.substringAfterLast('/'))
        if (out.exists()) return out.absolutePath
        try {
            context.assets.open(assetName).use { input ->
                FileOutputStream(out).use { output -> input.copyTo(output) }
            }
        } catch (e: Exception) {
            out.delete() // don't leave a truncated copy behind
            throw IllegalStateException(
                "Missing '$assetName'.\n\n" +
                    "Option A — rebuild: put the file at app/src/main/assets/$assetName " +
                    "and rebuild the app.\n" +
                    "Option B — no rebuild (better for the 1.14 GB .pte): use adb " +
                    "run-as to drop the file into the app's files directory " +
                    "(data/data/com.indra.krishiscan/files) on a debug build.",
                e,
            )
        }
        return out.absolutePath
    }

    private fun stripSpecialTokens(raw: String): String {
        var s = raw
        for (tok in SPECIAL_TOKENS) s = s.replace(tok, "")
        return s.trim()
    }
}

/**
 * Smoke test — the "done when": the app loads the .pte without crashing and
 * produces one tiny generation. Call it once from MainActivity.onCreate,
 * OFF the main thread, e.g.:
 *
 *     Thread {
 *         val report = runAdvisorySmokeTest(this)
 *         runOnUiThread { Toast.makeText(this, report, Toast.LENGTH_LONG).show() }
 *     }.start()
 *
 * Delete the call once the vision + Llama screens are wired together.
 * The tiny "OK" prompt is only a runner check — the real grounded prompt
 * (diagnosis + severity + region + language + advisory-database entry)
 * comes in a later step.
 */
fun runAdvisorySmokeTest(context: Context): String {
    val engine = AdvisoryEngine(context)
    return try {
        engine.load()
        val r = engine.generate("Reply with exactly this word: OK", maxNewTokens = 16)
        buildString {
            appendLine("LLAMA SMOKE TEST — loaded OK in ${engine.loadTimeMs} ms")
            appendLine("reply: ${r.text.take(200)}")
            appendLine(
                "TTFT ${r.timeToFirstTokenMs} ms · decode " +
                    "%.1f".format(r.decodeTokensPerSec) +
                    " tok/s · ${r.outputTokens} tokens · ${r.totalMs} ms total",
            )
        }
    } catch (e: Exception) {
        "LLAMA SMOKE TEST FAILED: ${e.message}"
    } finally {
        engine.close()
    }
}
